import { PLANS } from "@/types/plan";

export interface IndustryFaq {
  q: string;
  a: string;
}

export interface Industry {
  /** URL 은 `/for/{slug}` */
  slug: string;
  /** 업종명. h1 과 본문에서 쓴다 */
  name: string;
  /** `<title>` — 검색어를 앞쪽에, 브랜드를 뒤쪽에 */
  title: string;
  /** `<meta name="description">` */
  description: string;
  /**
   * 첫 문단 직답. **결론 먼저, 한 문장.**
   *
   * 답변엔진이 페이지 최상단에서 이 문장을 찾아 그대로 인용한다. 맥락에 기대지
   * 않고 그 자체로 완결된 사실이어야 한다 — "위에서 말한 그것"류는 추출되는 순간
   * 의미를 잃는다.
   */
  answer: string;
  /** 챗봇에 넣을 수 있는 자료 — 온보딩 템플릿의 재료이기도 하다 */
  materials: string[];
  /** 방문자가 물을 법한 것. "이렇게 답하도록 설정할 수 있다"는 뜻이지 실측이 아니다 */
  questions: string[];
  /** `PLANS` 의 name 과 일치해야 한다 */
  recommendedPlan: string;
  /** 왜 그 플랜인지 — 한 문장 */
  planReason: string;
  /**
   * 업종 특화 FAQ.
   *
   * ⚠️ **랜딩 FAQ(`component/landing/faq.tsx`)와 질문이 겹치면 안 된다.**
   * 같은 Q&A 를 여러 URL 에 FAQPage 로 중복 선언하면 스팸 신호가 된다.
   * 여기에는 그 업종에서만 나오는 질문을 둔다.
   */
  faq: IndustryFaq[];
}

/** `recommendedPlan` 이 실제 플랜인지 확인용 — 이름이 어긋나면 가격을 못 찾는다 */
export const planByName = (name: string) => PLANS.find((p) => p.name === name);

